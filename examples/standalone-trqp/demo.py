#!/usr/bin/env python3
"""Human-readable replay of the retained TRQP specification examination.

This presents source-pinned checks; it does not conduct a new assessment.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def summarize(result: dict) -> str:
    cases = {case["id"]: case["schema_valid"] for case in result["cases"]}
    required = {
        "minimal-required-fields": True,
        "missing-authority-negative-control": False,
        "historical-response-without-provenance": True,
    }
    if result["source_integrity"] != "verified" or any(
        cases.get(key) is not value for key, value in required.items()
    ):
        raise ValueError("Source identity or required demonstration controls changed")
    if not (
        result["api_example"]["schema_valid"] is True
        and result["api_example"]["requested_time_matches"] is False
        and result["https_example"]["schema_valid"] is True
        and result["https_example"]["requested_time_matches"] is True
    ):
        raise ValueError("Specification examples changed; reassess the narration")
    if (
        result["overall_assurance"] != "review-required"
        or result["runtime_authorization"] != "not-assessed"
        or result["authority_history"] != "not-assessed"
    ):
        raise ValueError("Assurance boundary changed; reassess the narration")
    return f"""RAHP specification examination: TRQP authorization responses
Source snapshot: {result['target_commit']}

QUESTION
What does a schema-valid authorization response actually establish?

1. SOURCE INTEGRITY
Retained upstream source: VERIFIED (manifest hashes and Git blob identities).

2. REPLAYABLE CHECKS
Required-fields response: schema VALID.
Missing-authority negative control: schema INVALID.
Historical response without provenance: schema VALID.
Upstream API example: schema VALID, but requested time differs from query.
Upstream HTTPS example: schema VALID, and requested time matches query.

3. DOCUMENTED REVIEW FINDINGS
F-001: Schema validity does not establish authority history/current permission.
       Disposition: OPEN; implementation guidance / deployment evidence needed.
F-002: The API example does not preserve queried historical time.
       Disposition: OPEN; specification-editor clarification needed.

4. ASSURANCE BOUNDARY
Overall posture: REVIEW REQUIRED.
Runtime authorization: NOT ASSESSED. Authority history: NOT ASSESSED.
These checks do NOT demonstrate a live service defect, TRQP conformance,
or independent assurance. Findings are existing reviewer judgments, not
conclusions automatically generated by this presentation script.

NEXT
Inspect examples/standalone-trqp/pressure-test.yaml for source observations,
reasoning, evidence requests and retest conditions.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="compare with retained expected replay")
    args = parser.parse_args()
    from replay import replay
    result = replay()
    if args.check:
        expected = json.loads((HERE / "expected-replay.json").read_text(encoding="utf-8"))
        if result != expected:
            raise ValueError("Replay differs from retained expected result")
    print(summarize(result))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
